CREATE TABLE IF NOT EXISTS orders (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    public_ref CHAR(28) NOT NULL,
    customer_id INT UNSIGNED NULL,
    guest_token_hash CHAR(64) NULL,
    status VARCHAR(32) NOT NULL,
    payment_status VARCHAR(32) NOT NULL,
    payment_method VARCHAR(32) NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'INR',
    item_subtotal DECIMAL(12,2) NOT NULL,
    discount_total DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    shipping_total DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    tax_total DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    grand_total DECIMAL(12,2) NOT NULL,
    coupon_code VARCHAR(40) NULL,
    contact_name VARCHAR(120) NOT NULL,
    contact_email VARCHAR(255) NOT NULL,
    contact_mobile CHAR(10) NOT NULL,
    shipping_name VARCHAR(120) NOT NULL,
    shipping_phone CHAR(10) NOT NULL,
    shipping_line1 VARCHAR(160) NOT NULL,
    shipping_line2 VARCHAR(160) NULL,
    shipping_city VARCHAR(80) NOT NULL,
    shipping_state VARCHAR(80) NOT NULL,
    shipping_pincode CHAR(6) NOT NULL,
    shipping_country VARCHAR(64) NOT NULL DEFAULT 'India',
    billing_same TINYINT(1) NOT NULL DEFAULT 1,
    billing_name VARCHAR(120) NOT NULL,
    billing_phone CHAR(10) NOT NULL,
    billing_line1 VARCHAR(160) NOT NULL,
    billing_line2 VARCHAR(160) NULL,
    billing_city VARCHAR(80) NOT NULL,
    billing_state VARCHAR(80) NOT NULL,
    billing_pincode CHAR(6) NOT NULL,
    billing_country VARCHAR(64) NOT NULL DEFAULT 'India',
    idempotency_key VARCHAR(80) NULL,
    cart_id INT UNSIGNED NULL,
    shipping_source VARCHAR(40) NOT NULL,
    tax_source VARCHAR(40) NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_orders_public_ref (public_ref),
    UNIQUE KEY uq_orders_idempotency (idempotency_key),
    INDEX idx_orders_customer (customer_id),
    INDEX idx_orders_guest (guest_token_hash),
    INDEX idx_orders_status (status),
    CONSTRAINT fk_orders_customer
        FOREIGN KEY (customer_id) REFERENCES customers(id)
        ON UPDATE CASCADE
        ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
